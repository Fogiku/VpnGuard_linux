type UpdateEvent struct {
	At          string `json:"at"`
	Version     string `json:"version"`
	Status      string `json:"status"`
	Description string `json:"description"`
}

func updateHistory() []UpdateEvent {
	var events []UpdateEvent
	loadJSON("updates.json", &events)
	if events == nil {
		return []UpdateEvent{}
	}
	return events
}
